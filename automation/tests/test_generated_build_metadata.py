import subprocess
from pathlib import Path

import pytest

from openhands_factory.git_workflow import GitWorkflow

RELATIVE = "frontend/src/app/generated/build-info.generated.ts"
HEADER = "// Generated by scripts/generate-help-about-data.mjs. Do not edit by hand.\n"


def metadata(sha: str, version: str = "2.0.0") -> str:
    return (
        HEADER
        + f"export const GENERATED_APP_VERSION = '{version}';\n"
        + f"export const GENERATED_BUILD_NUMBER = 'local.{sha[:12]}';\n"
    )


def git(repository: Path, *arguments: str) -> str:
    return subprocess.check_output(["git", *arguments], cwd=repository, text=True).strip()


@pytest.fixture
def repository(tmp_path):
    git(tmp_path, "init", "-q", "-b", "main")
    git(tmp_path, "config", "user.name", "test")
    git(tmp_path, "config", "user.email", "test@example.test")
    generated = tmp_path / RELATIVE
    generated.parent.mkdir(parents=True)
    generated.write_text(metadata("000000000000"))
    (tmp_path / "source.ts").write_text("original source\n")
    git(tmp_path, "add", ".")
    git(tmp_path, "commit", "-qm", "baseline")
    return tmp_path


def test_only_current_head_build_output_is_restored(repository):
    generated = repository / RELATIVE
    generated.write_text(metadata(git(repository, "rev-parse", "HEAD")))
    (repository / "source.ts").write_text("genuine pending source change\n")
    assert GitWorkflow(repository, "main").discard_transient_build_metadata()
    assert generated.read_text() == metadata("000000000000")
    assert (repository / "source.ts").read_text() == "genuine pending source change\n"
    assert git(repository, "diff", "--name-only") == "source.ts"


@pytest.mark.parametrize(
    "change", ["staged", "version", "code", "wrong-head", "executable", "line-endings"]
)
def test_meaningful_or_unproven_generated_file_changes_are_preserved(repository, change):
    generated = repository / RELATIVE
    content = metadata(git(repository, "rev-parse", "HEAD"))
    if change == "version":
        content = content.replace("'2.0.0'", "'3.0.0'")
    elif change == "code":
        content += "export const customBehaviour = true;\n"
    elif change == "wrong-head":
        content = metadata("111111111111")
    if change == "line-endings":
        generated.write_bytes(content.replace("\n", "\r\n").encode())
    else:
        generated.write_text(content)
    if change == "staged":
        git(repository, "add", RELATIVE)
    elif change == "executable":
        generated.chmod(0o755)
    assert not GitWorkflow(repository, "main").discard_transient_build_metadata()
    assert generated.read_text() == content


def test_symlink_and_untracked_metadata_are_not_restored(repository):
    generated = repository / RELATIVE
    outside = repository.parent / "outside.txt"
    outside.write_text("preserve this file")
    generated.unlink()
    generated.symlink_to(outside)
    assert not GitWorkflow(repository, "main").discard_transient_build_metadata()
    assert outside.read_text() == "preserve this file"
    generated.unlink()
    git(repository, "rm", RELATIVE)
    git(repository, "commit", "-qm", "remove generated file")
    generated.parent.mkdir(parents=True, exist_ok=True)
    content = metadata(git(repository, "rev-parse", "HEAD"))
    generated.write_text(content)
    assert not GitWorkflow(repository, "main").discard_transient_build_metadata()
    assert generated.read_text() == content


def test_metadata_through_a_symlinked_parent_is_preserved(repository):
    generated = repository / RELATIVE
    real_directory = repository / "real-generated"
    generated.parent.rename(real_directory)
    generated.parent.symlink_to(real_directory, target_is_directory=True)
    content = metadata(git(repository, "rev-parse", "HEAD"))
    generated.write_text(content)
    assert not GitWorkflow(repository, "main").discard_transient_build_metadata()
    assert generated.parent.is_symlink()
    assert generated.read_text() == content


def test_dirty_generated_metadata_no_longer_blocks_real_base_merge(repository, tmp_path):
    remote = tmp_path / "remote.git"
    remote.mkdir()
    git(remote, "init", "--bare", "-q")
    git(repository, "remote", "add", "origin", str(remote))
    git(repository, "push", "-q", "-u", "origin", "main")
    git(repository, "switch", "-qc", "fix/feature")
    (repository / "source.ts").write_text("preserve feature intent\n")
    git(repository, "commit", "-qam", "feature")
    git(repository, "switch", "-q", "main")
    (repository / RELATIVE).write_text(metadata("111111111111"))
    git(repository, "commit", "-qam", "updated generated base")
    git(repository, "push", "-q", "origin", "main")
    git(repository, "switch", "-q", "fix/feature")
    (repository / RELATIVE).write_text(metadata(git(repository, "rev-parse", "HEAD")))
    assert not GitWorkflow(repository, "main").merge_base_for_repair()
    assert (repository / ".git/MERGE_HEAD").exists()
    assert (repository / RELATIVE).read_text() == metadata("111111111111")
    assert (repository / "source.ts").read_text() == "preserve feature intent\n"
